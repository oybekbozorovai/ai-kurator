def format_preset(preset: dict) -> str:
    """Tayyor yo'nalishni o'quvchiga ko'rsatish uchun matn formatlaydi."""
    lines = [f"🎬 {preset['name']} — Video SEO\n"]

    titles = preset.get("titles") or []
    if len(titles) == 1:
        lines.append("📌 Video nomi:")
        lines.append(str(titles[0]))
    elif titles:
        lines.append("📌 Video nomi variantlari:")
        for i, title in enumerate(titles, 1):
            lines.append(f"{i}. {title}")

    description = preset.get("description") or ""
    if description:
        lines.append("\n📝 Video opisaniyesi:")
        lines.append(str(description))

    tags = preset.get("tags") or []
    if tags:
        lines.append("\n🏷 Teglar:")
        lines.append(", ".join(str(t) for t in tags))

    return "\n".join(lines)
